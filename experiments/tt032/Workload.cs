using System.Data.Common;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using TurboTest.EFCore;

namespace CompetitiveBaseline;

public sealed class Context(DbContextOptions<Context> options) : DbContext(options);

// Fixed inputs and an independently constructed expected result, not hashes copied from the database.
static class Workload
{
    public const string Version = "tt032-relational-v1";
    public static int MigrationCalls, SeedCalls;
    public static readonly TtBaselineDefinition<Context> Baseline = new(Version, TtSchemaInitialization.Caller,
        async (context, token) => { await Migrate(context, token); await Seed(context, token); });
    public const string Schema = """
        CREATE TABLE IF NOT EXISTS "SchemaVersion" ("Id" integer PRIMARY KEY);
        CREATE TABLE IF NOT EXISTS "Parents" ("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "Name" text NOT NULL, "Priority" integer NOT NULL);
        CREATE TABLE IF NOT EXISTS "Children" ("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "ParentId" integer NOT NULL REFERENCES "Parents", "Name" text NOT NULL, "Enabled" boolean NOT NULL);
        CREATE TABLE IF NOT EXISTS "Notes" ("Id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "ChildId" integer NOT NULL REFERENCES "Children", "Body" text NOT NULL, "Revision" integer NOT NULL);
        INSERT INTO "SchemaVersion" VALUES (1) ON CONFLICT DO NOTHING;
        """;
    public const string SeedSql = """
        INSERT INTO "Parents" SELECT i,'seed-parent-'||i,i*3 FROM generate_series(1,32) i;
        INSERT INTO "Children" SELECT i,1+(i-1)%32,'seed-child-'||i,i%2=0 FROM generate_series(1,64) i;
        INSERT INTO "Notes" SELECT i,1+(i-1)%64,'seed-note-'||i,i*7 FROM generate_series(1,128) i;
        SELECT setval('"Parents_Id_seq"',1000,true),setval('"Children_Id_seq"',2000,true),setval('"Notes_Id_seq"',3000,true);
        """;
    public static async Task Migrate(Context context, CancellationToken token = default)
    { Interlocked.Increment(ref MigrationCalls); await context.Database.ExecuteSqlRawAsync(Schema, token); }
    public static async Task Seed(Context context, CancellationToken token = default)
    { Interlocked.Increment(ref SeedCalls); await context.Database.ExecuteSqlRawAsync(SeedSql, token); }
    public static Context New(NpgsqlDataSource source) => new(new DbContextOptionsBuilder<Context>().UseNpgsql(source).Options);
    public static async Task<NpgsqlConnection> Open(Context context, CancellationToken token = default)
    { await context.Database.OpenConnectionAsync(token); return (NpgsqlConnection)context.Database.GetDbConnection(); }
    public static async Task Execute(NpgsqlConnection c, string sql, CancellationToken token = default)
    { await using var cmd = new NpgsqlCommand(sql, c) { CommandTimeout = 15 }; await cmd.ExecuteNonQueryAsync(token); }
    public static async Task<T> Scalar<T>(NpgsqlConnection c, string sql, CancellationToken token = default)
    { await using var cmd = new NpgsqlCommand(sql, c) { CommandTimeout = 15 }; return (T)(await cmd.ExecuteScalarAsync(token))!; }

    static readonly string[] ExpectedSeeds = [
        string.Join('|', Enumerable.Range(1,32).Select(i=>$"{i}:seed-parent-{i}:{i*3}")),
        string.Join('|', Enumerable.Range(1,64).Select(i=>$"{i}:{1+(i-1)%32}:seed-child-{i}:{(i%2==0 ? "true":"false")}")),
        string.Join('|', Enumerable.Range(1,128).Select(i=>$"{i}:{1+(i-1)%64}:seed-note-{i}:{i*7}"))];
    const string ReadSeeds = """
        SELECT string_agg("Id"||':'||"Name"||':'||"Priority",'|' ORDER BY "Id") FROM "Parents";
        SELECT string_agg("Id"||':'||"ParentId"||':'||"Name"||':'||"Enabled",'|' ORDER BY "Id") FROM "Children";
        SELECT string_agg("Id"||':'||"ChildId"||':'||"Body"||':'||"Revision",'|' ORDER BY "Id") FROM "Notes";
        SELECT last_value,is_called FROM "Parents_Id_seq";
        SELECT last_value,is_called FROM "Children_Id_seq";
        SELECT last_value,is_called FROM "Notes_Id_seq";
        SELECT string_agg("Id"::text,',' ORDER BY "Id") FROM "SchemaVersion";
        SELECT count(*) FROM information_schema.columns WHERE table_schema='public' AND column_name='unexpected';
        """;
    public static async Task CheckBaseline(NpgsqlConnection c, CancellationToken token = default)
    {
        await using var cmd = new NpgsqlCommand(ReadSeeds,c);
        await using var r = await cmd.ExecuteReaderAsync(token);
        for (var i=0;i<3;i++)
        {
            Require(await r.ReadAsync(token) && !r.IsDBNull(0) && r.GetString(0)==ExpectedSeeds[i], "SeedState");
            Require(await r.NextResultAsync(token), "BaselineResults");
        }
        for (var i=0;i<3;i++)
        {
            Require(await r.ReadAsync(token) && r.GetInt64(0)==(i+1)*1000 && r.GetBoolean(1), "SequenceState");
            Require(await r.NextResultAsync(token), "BaselineResults");
        }
        Require(await r.ReadAsync(token) && r.GetString(0)=="1", "MigrationState");
        await r.NextResultAsync(token);
        Require(await r.ReadAsync(token) && r.GetInt64(0)==0, "SchemaState");
    }

    // Both sessions stay open; each statement autocommits. Session two observes session one's writes.
    public static async Task Mutate(NpgsqlConnection a, NpgsqlConnection b, string marker, CancellationToken token=default)
    {
        await using var first = new NpgsqlCommand("""
            UPDATE "Parents" SET "Name"='changed-seed',"Priority"=91 WHERE "Id"=1;
            DELETE FROM "Notes" WHERE "Id"=1;
            INSERT INTO "Parents"("Name","Priority") SELECT @m||'-parent-'||i,31+i FROM generate_series(1,100) i;
            """,a);
        first.Parameters.AddWithValue("m",marker); await first.ExecuteNonQueryAsync(token);
        await using var second = new NpgsqlCommand("""
            INSERT INTO "Children"("ParentId","Name","Enabled") SELECT 1000+i,@m||'-child-'||i,false FROM generate_series(1,20) i;
            INSERT INTO "Notes"("ChildId","Body","Revision") SELECT 2000+i,@m||'-note-'||i,71 FROM generate_series(1,10) i;
            """,b);
        second.Parameters.AddWithValue("m",marker); await second.ExecuteNonQueryAsync(token);
    }
    public static async Task CheckMutated(NpgsqlConnection c,string marker,CancellationToken token=default)
    {
        await using var cmd=new NpgsqlCommand("""
            SELECT count(*),count(*) FILTER (WHERE "Id" BETWEEN 1001 AND 1100 AND "Name"=@m||'-parent-'||("Id"-1000) AND "Priority"=31+"Id"-1000),count(*) FILTER(WHERE "Id"=1 AND "Name"='changed-seed' AND "Priority"=91) FROM "Parents";
            SELECT count(*),count(*) FILTER (WHERE "Id" BETWEEN 2001 AND 2020 AND "ParentId"=1000+"Id"-2000 AND "Name"=@m||'-child-'||("Id"-2000) AND NOT "Enabled") FROM "Children";
            SELECT count(*),count(*) FILTER (WHERE "Id" BETWEEN 3001 AND 3010 AND "ChildId"=2000+"Id"-3000 AND "Body"=@m||'-note-'||("Id"-3000) AND "Revision"=71),count(*) FILTER(WHERE "Id"=1) FROM "Notes";
            """,c);
        cmd.Parameters.AddWithValue("m",marker);
        await using var r=await cmd.ExecuteReaderAsync(token);
        Require(await r.ReadAsync(token)&&r.GetInt64(0)==132&&r.GetInt64(1)==100&&r.GetInt64(2)==1,"ParentWork");
        await r.NextResultAsync(token);
        Require(await r.ReadAsync(token)&&r.GetInt64(0)==84&&r.GetInt64(1)==20,"ChildWork");
        await r.NextResultAsync(token);
        Require(await r.ReadAsync(token)&&r.GetInt64(0)==137&&r.GetInt64(1)==10&&r.GetInt64(2)==0,"NoteWork");
    }
    public static void Require(bool condition,string rule) { if(!condition) throw new InvalidDataException(rule); }
}
